-- با ثبت ساکن، حساب ورود ساخته می‌شود: نام کاربری = شماره موبایل، رمز اولیه = شماره واحد.
-- تا ساکن رمز را از «تنظیمات» عوض نکرده، must_change_password روشن می‌ماند و اپ او را به
-- تغییر رمز هدایت می‌کند.
ALTER TABLE identity.users ADD COLUMN IF NOT EXISTS must_change_password boolean NOT NULL DEFAULT false;
