/**
 * داده‌ی نمونه (بتا) فقط وقتی نمایش داده می‌شود که صراحتاً روشن شده باشد: VITE_DEMO_DATA=true
 * (مثلاً روی سرور دمو). در حالت عادی هر ساختمان تازه «خام» است: همه‌ی شمارنده‌ها ۰ و فهرست‌ها خالی؛
 * مدیر/حسابدار اطلاعات را دستی وارد می‌کند یا از فایل حسابداری (اکسل/CSV) وارد می‌کند.
 */
export const DEMO_DATA = import.meta.env?.VITE_DEMO_DATA === 'true'

/** در حالت دمو مقدار نمونه، وگرنه مقدار خام (خالی/صفر) */
export function demo<T>(sample: T, empty: T): T {
  return DEMO_DATA ? sample : empty
}
